#!/usr/bin/env python3
"""Validate the native UI locale source and generate its deterministic C catalog."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "native_c" / "locales" / "ui-translations.json"
OUTPUT = ROOT / "native_c" / "src" / "i18n.c"
LOCALES = ("en", "de", "fr", "es", "pt", "zh")
PLACEHOLDER = re.compile(
    r"%(?:[-+#0 ]*[0-9]*\\.?[0-9]*(?:hh|h|ll|l|I64|z|t|j)?[diuoxXfFeEgGaAcspn%])"
)


def c_wide(text: str) -> str:
    if "\0" in text:
        raise ValueError("embedded NUL cannot be emitted as a C string")
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'L"{escaped}"'


def generate() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    phrases = data["source_phrases"]
    locales = data["locales"]
    if not isinstance(phrases, list) or not phrases or not all(isinstance(x, str) for x in phrases):
        raise ValueError("source_phrases must be a non-empty string array")
    if len(set(phrases)) != len(phrases):
        raise ValueError("source phrase keys must be unique")
    if set(locales) != set(LOCALES):
        raise ValueError(f"expected locale keys {LOCALES}, received {tuple(locales)}")

    for code in LOCALES:
        strings = locales[code]["translations"]
        if len(strings) != len(phrases):
            raise ValueError(f"{code}: expected {len(phrases)} translations, got {len(strings)}")
        for index, (source, translated) in enumerate(zip(phrases, strings)):
            if not isinstance(translated, str) or not translated:
                raise ValueError(f"{code}[{index}] is empty or not a string")
            if PLACEHOLDER.findall(source) != PLACEHOLDER.findall(translated):
                raise ValueError(f"{code}[{index}] changes format placeholders: {source!r} -> {translated!r}")
            if source.count("\n") != translated.count("\n") or source.count("\r") != translated.count("\r"):
                raise ValueError(f"{code}[{index}] changes line breaks")

    names = {
        "uk": "Українська",
        "en": "English",
        "de": "Deutsch",
        "fr": "Français",
        "es": "Español",
        "pt": "Português",
        "zh": "简体中文",
    }
    pairs = sorted(zip(phrases, *[locales[code]["translations"] for code in LOCALES]), key=lambda row: row[0].encode("utf-16-be"))
    out = [
        '/* Generated by scripts/generate_i18n.py from native_c/locales/ui-translations.json. */',
        '#include "i18n.h"',
        '#include <string.h>',
        '',
        'typedef struct { const wchar_t *source; const wchar_t *text[6]; } ZDTranslation;',
        'static const ZDLocale g_locales[ZD_LOCALE_COUNT] = {',
    ]
    for code in ("uk",) + LOCALES:
        out.append(f'    {{"{code}", {c_wide(names[code])}}},')
    out.extend(['};', '', 'static const ZDTranslation g_translations[] = {'])
    for row in pairs:
        source, *translated = row
        out.append('    {' + c_wide(source) + ', {' + ', '.join(c_wide(x) for x in translated) + '}},')
    out.extend([
        '};',
        '',
        'const ZDLocale *zd_i18n_locales(size_t *count) {',
        '    if (count) *count = ZD_LOCALE_COUNT;',
        '    return g_locales;',
        '}',
        '',
        'const char *zd_i18n_code_at(size_t index) {',
        '    return index < ZD_LOCALE_COUNT ? g_locales[index].code : g_locales[0].code;',
        '}',
        '',
        'int zd_i18n_index(const char *code) {',
        '    if (!code) return 0;',
        '    for (int i = 0; i < ZD_LOCALE_COUNT; ++i)',
        '        if (strcmp(code, g_locales[i].code) == 0) return i;',
        '    return 0;',
        '}',
        '',
        'const wchar_t *zd_i18n_translate(const char *locale, const wchar_t *source) {',
        '    if (!source) return L"";',
        '    int index = zd_i18n_index(locale);',
        '    if (index == 0) return source;',
        '    size_t lo = 0, hi = sizeof(g_translations) / sizeof(g_translations[0]);',
        '    while (lo < hi) {',
        '        size_t mid = lo + (hi - lo) / 2;',
        '        int cmp = wcscmp(source, g_translations[mid].source);',
        '        if (cmp == 0) return g_translations[mid].text[index - 1];',
        '        if (cmp < 0) hi = mid; else lo = mid + 1;',
        '    }',
        '    return source;',
        '}',
        '',
    ])
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated C is stale")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"Stale generated file: {OUTPUT}")
            return 1
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print(f"Localization catalog generated: {OUTPUT} ({len(json.loads(SOURCE.read_text(encoding='utf-8'))['source_phrases'])} keys, {len(LOCALES)} locales)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
